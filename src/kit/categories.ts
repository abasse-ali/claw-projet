export function categorize(label: string): string {
  const plain = String(label || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");

  for (const [category, keywords] of Object.entries(CATEGORY_KEYWORDS)) {
    if (keywords.some((kw) => plain.includes(kw))) {
      return category;
    }
  }
  return "Autre";
}